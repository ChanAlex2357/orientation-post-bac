 *   Leur statut suit quand même le tableau 16 : A_CONFIRMER sans référence
 *   correspond au cas réel « Arrêté en cours » (28 lignes du relevé Haute
 *   Matsiatra), NON_VERIFIEE au cas « filière absente des listes publiées ».
